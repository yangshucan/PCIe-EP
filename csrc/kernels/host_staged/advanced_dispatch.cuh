#pragma once

#include "advanced_layout.cuh"

namespace pcie_ep::host_staged {

struct alignas(16) AdvancedLocalStage {
    alignas(16) TokenMetadata metadata;
    // Specialized roles publish ticket + 1; zero means FREE. Matching the
    // generation in one acquire prevents an old READY/new plain-ticket ABA.
    // The homogeneous CTA does not use this field for stage admission.
    int ready;
    int workers_done;
    int host_readers_done;
    int metadata_done;
    int ticket;
    int source_rank;
    int payload_slot;
    int output_row;
    int descriptor_ordinal;
    int ack_sent;
    float scale;
    std::uint64_t payload_sequence;
    std::uint64_t endpoints;
    int endpoint_ordinals[kNumMaxEndpoints];
};

struct alignas(16) AdvancedLocalQueues {
    AdvancedLocalStage tx[kNumMaxLocalStages];
    AdvancedLocalStage rx[kNumMaxLocalStages];
    int abort;
    int tx_finished;
    int rx_finished;
    int tx_action;
    int rx_action;
    int tx_stage;
    int rx_stage;
};

constexpr std::size_t kNumAdvancedQueueBytes = (sizeof(AdvancedLocalQueues) + 15) / 16 * 16;

inline std::size_t advanced_shared_memory_bytes(int hidden, int stages, bool fuse_receive_expand) {
    return kNumAdvancedQueueBytes +
        (fuse_receive_expand ? std::size_t(hidden) * 2 * stages : 0);
}

__device__ inline void metadata_copy_warp(TokenMetadata* destination, const TokenMetadata* source, int lane) {
    constexpr int kNumVectors = sizeof(TokenMetadata) / sizeof(uint4);
    for (int vector = lane; vector < kNumVectors; vector += 32)
        reinterpret_cast<uint4*>(destination)[vector] = reinterpret_cast<const uint4*>(source)[vector];
}

__device__ inline void prepare_current_metadata(
    AdvancedDeviceState& state, TokenMetadata* destination, int token, int lane
) {
    const auto* plan = state.base.route_plan + token;
    if (!state.source_fusion) {
        metadata_copy_warp(destination, plan, lane);
    } else {
        // Counts/ordinals remain precomputed. Expert IDs, rank mask and current
        // weights are generated by this control warp from the live inputs.
        auto* output_words = reinterpret_cast<std::uint32_t*>(destination);
        const auto* input_words = reinterpret_cast<const std::uint32_t*>(plan);
        constexpr int kNumPrefixWords = offsetof(TokenMetadata, expert_indices) / 4;
        for (int index = lane; index < int(sizeof(TokenMetadata) / 4); index += 32)
            output_words[index] = index < kNumPrefixWords ? input_words[index] : 0;
    }
    __syncwarp();
    unsigned destination_mask = 0;
    if (lane < state.base.layout.num_topk) {
        const int expert = state.source_fusion ?
            int(state.topk_indices[token * state.base.layout.num_topk + lane]) : destination->expert_indices[lane];
        destination->expert_indices[lane] = expert;
        destination->weights[lane] = state.topk_weights ? state.topk_weights[token * state.base.layout.num_topk + lane] : 1.0f;
        if (expert >= 0)
            destination_mask = 1u << (expert / (state.base.layout.num_experts / state.base.layout.num_ranks));
    }
    destination_mask = __reduce_or_sync(0xffffffffu, destination_mask);
    if (!lane && state.source_fusion)
        destination->destination_mask = destination_mask;
    __syncwarp();
}

__device__ inline void copy_tx_payload(
    AdvancedDeviceState& state, AdvancedLocalStage& stage, int channel, int worker_index, int workers
) {
    const int hidden = state.base.layout.num_hidden;
    const int token = stage.metadata.token_index;
    const std::size_t slot = std::size_t(channel) * state.base.layout.num_payload_slots + stage.payload_slot;
    auto* destination = reinterpret_cast<std::uint8_t*>(state.base.mapped_source_buffers[state.base.local_rank] +
        state.shared.source_payload_offset) + slot * state.shared.payload_stride_bytes;
    if (state.payload_dtype) {
        const auto* input = state.fp8_payload + std::size_t(token) * hidden;
        if (hidden % 16 == 0) {
            for (int index = worker_index; index < hidden / 16; index += workers)
                reinterpret_cast<uint4*>(destination)[index] = reinterpret_cast<const uint4*>(input)[index];
        } else {
            for (int index = worker_index; index < hidden; index += workers)
                destination[index] = input[index];
        }
    } else {
        const auto* input = state.input_payload + std::size_t(token) * hidden;
        if (hidden % 8 == 0) {
            for (int index = worker_index; index < hidden / 8; index += workers)
                reinterpret_cast<uint4*>(destination)[index] = reinterpret_cast<const uint4*>(input)[index];
        } else {
            for (int index = worker_index; index < hidden; index += workers)
                reinterpret_cast<std::uint16_t*>(destination)[index] = input[index];
        }
    }
}

__device__ inline void copy_rx_payload(
    AdvancedDeviceState& state, AdvancedLocalStage& stage, int channel,
    std::uint16_t* local_tile, int worker_index, int workers
) {
    const int hidden = state.base.layout.num_hidden;
    const auto* source = receive_payload(state, stage.source_rank, channel, stage.payload_slot);
    auto* destination = state.fuse_receive_expand ? local_tile :
        state.base.unique_payload + std::size_t(stage.output_row) * hidden;
    if (state.payload_dtype) {
        for (int index = worker_index; index < hidden; index += workers)
            destination[index] = dequantize_fp8_to_bf16(source[index], stage.scale);
    } else if (hidden % 8 == 0) {
        for (int index = worker_index; index < hidden / 8; index += workers)
            reinterpret_cast<uint4*>(destination)[index] = reinterpret_cast<const uint4*>(source)[index];
    } else {
        for (int index = worker_index; index < hidden; index += workers)
            destination[index] = reinterpret_cast<const std::uint16_t*>(source)[index];
    }
}

__device__ inline void scatter_rx_tile(
    AdvancedDeviceState& state, AdvancedLocalStage& stage, std::uint16_t* tile,
    int worker_index, int workers, int* aborted
) {
    const int experts_per_rank = state.base.layout.num_experts / state.base.layout.num_ranks;
    for (int branch = 0; branch < state.base.layout.num_topk; ++branch) {
        const int expert = stage.metadata.expert_indices[branch] - state.base.local_rank * experts_per_rank;
        if (expert < 0 || expert >= experts_per_rank)
            continue;
        const int row = state.base.expert_offsets[expert] +
            state.base.source_expert_prefix[stage.source_rank * experts_per_rank + expert] + stage.metadata.expert_ordinals[branch];
        if (row >= state.expanded_capacity) {
            if (!worker_index) {
                advanced_record_error(state, kErrorExpandedCapacity);
                local_store(aborted, 1);
            }
            return;
        }
        for (int hidden = worker_index; hidden < state.base.layout.num_hidden; hidden += workers)
            state.expanded_payload[std::size_t(row) * state.base.layout.num_hidden + hidden] = tile[hidden];
        if (!worker_index)
            advanced_store_expanded_metadata(state, stage.metadata, stage.source_rank, branch, row, expert);
    }
}

__device__ inline bool tx_payload_available(
    AdvancedDeviceState& state, int channel, int produced, int* endpoint_reserved
) {
    const int slots = state.base.layout.num_payload_slots;
    const int descriptors = state.base.layout.num_descriptor_slots;
    const int stride = state.base.layout.num_max_tokens_per_rank;
    const auto epoch = *state.base.epoch;
    auto* own = state.base.mapped_source_buffers[state.base.local_rank];
    if (produced >= slots) {
        const int token = state.channel_remote_indices[channel * stride + produced - slots];
        const auto targets = advanced_endpoint_mask(state, state.base.route_plan[token].destination_mask);
        for (int endpoint = 0; endpoint < state.shared.num_endpoints; ++endpoint) {
            if ((targets & (1ull << endpoint)) && load_acquire_system(signal_value_ptr(own,
                state.shared.source_ack_offset, (channel * slots + produced % slots) * state.shared.num_endpoints + endpoint)) !=
                advanced_sequence(epoch, token))
                return false;
        }
    }
    const int token = state.channel_remote_indices[channel * stride + produced];
    const auto targets = advanced_endpoint_mask(state, state.base.route_plan[token].destination_mask);
    for (int endpoint = 0; endpoint < state.shared.num_endpoints; ++endpoint) {
        if ((targets & (1ull << endpoint)) && endpoint_reserved[endpoint] >= descriptors) {
            auto* descriptor = source_descriptor(state, state.base.local_rank, channel, endpoint, endpoint_reserved[endpoint]);
            if (load_acquire_system(&descriptor->consumed_sequence) !=
                advanced_sequence(epoch, endpoint_reserved[endpoint] - descriptors))
                return false;
        }
    }
    return true;
}

__device__ inline bool tx_drained(AdvancedDeviceState& state, int channel, int produced) {
    const int slots = state.base.layout.num_payload_slots;
    const auto epoch = *state.base.epoch;
    auto* own = state.base.mapped_source_buffers[state.base.local_rank];
    for (int ordinal = max(0, produced - slots); ordinal < produced; ++ordinal) {
        const int token = state.channel_remote_indices[channel * state.base.layout.num_max_tokens_per_rank + ordinal];
        const auto targets = advanced_endpoint_mask(state, state.base.route_plan[token].destination_mask);
        for (int endpoint = 0; endpoint < state.shared.num_endpoints; ++endpoint) {
            if ((targets & (1ull << endpoint)) && load_acquire_system(signal_value_ptr(own,
                state.shared.source_ack_offset, (channel * slots + ordinal % slots) * state.shared.num_endpoints + endpoint)) !=
                advanced_sequence(epoch, token))
                return false;
        }
    }
    if (state.numa_mode) {
        for (int node = 0; node < state.num_numa_nodes; ++node) {
            // Even a zero-work relay flow must acquire and consume this epoch's
            // endpoint counts before a later dispatch may overwrite its mailbox.
            if (load_acquire_system(signal_value_ptr(own, state.shared.relay_drained_offset,
                    channel * state.num_numa_nodes + node)) != epoch)
                return false;
        }
    }
    return true;
}

__device__ void advanced_tx_control(AdvancedDeviceState state, AdvancedLocalQueues& queues, int channel, int lane) {
    int reserved[kNumMaxEndpoints] = {};
    int prepared = 0, published = 0, rounds = 0;
    const int num_tokens = state.channel_num_remote_tokens[channel];
    const auto epoch = *state.base.epoch;
    const auto start = global_time_ns();
    auto* statistics = state.channel_statistics + channel * kNumStatisticsFields;
    auto* own = state.base.mapped_source_buffers[state.base.local_rank];
    if (!lane)
        state.channel_timestamps_ns[channel * 2] = start;

    while (true) {
        if (!lane) {
            queues.tx_action = 0;
            if (local_load(&queues.abort)) {
                store_release_system(signal_value_ptr(own, state.shared.channel_abort_offset, channel), epoch);
                local_store(&queues.tx_finished, 1);
                queues.tx_action = -1;
            } else {
                // Publish strictly in reservation order, after every worker
                // fenced its own host stores and the metadata warp completed.
                if (published < prepared) {
                    auto& stage = queues.tx[published % state.stages];
                    if (local_load(&stage.workers_done) == 3 && local_load(&stage.metadata_done)) {
                        for (int endpoint = 0; endpoint < state.shared.num_endpoints; ++endpoint) {
                            if (stage.endpoints & (1ull << endpoint)) {
                                auto* descriptor = source_descriptor(state, state.base.local_rank, channel,
                                    endpoint, stage.endpoint_ordinals[endpoint]);
                                descriptor->payload_sequence = stage.payload_sequence;
                                descriptor->payload_slot = stage.payload_slot;
                                descriptor->token_index = stage.metadata.token_index;
                                descriptor->rank_ordinal = endpoint < state.base.layout.num_ranks ? stage.metadata.rank_ordinals[endpoint] : 0;
                                store_release_system(&descriptor->ready_sequence,
                                    advanced_sequence(epoch, stage.endpoint_ordinals[endpoint]));
                                statistics[7]++;
                            }
                        }
                        statistics[kNumHostPayloadWritesField]++;
                        statistics[kNumDescriptorsPublishedField] += __popcll(stage.metadata.destination_mask & ~(1ull << state.base.local_rank));
                        local_store(&stage.ready, 0);
                        ++published;
                    }
                }
                if (prepared < num_tokens) {
                    auto& stage = queues.tx[prepared % state.stages];
                    if (!local_load(&stage.ready)) {
                        if (tx_payload_available(state, channel, prepared, reserved)) {
                            const int token = state.channel_remote_indices[channel * state.base.layout.num_max_tokens_per_rank + prepared];
                            stage.ticket = prepared;
                            stage.payload_slot = prepared % state.base.layout.num_payload_slots;
                            stage.payload_sequence = advanced_sequence(epoch, token);
                            stage.endpoints = advanced_endpoint_mask(state, state.base.route_plan[token].destination_mask);
                            for (int endpoint = 0; endpoint < state.shared.num_endpoints; ++endpoint)
                                if (stage.endpoints & (1ull << endpoint))
                                    stage.endpoint_ordinals[endpoint] = reserved[endpoint]++;
                            stage.metadata_done = 0;
                            stage.workers_done = 0;
                            queues.tx_stage = prepared % state.stages;
                            queues.tx_action = 1;
                        } else {
                            statistics[5]++;
                        }
                    } else {
                        statistics[6]++;
                    }
                }
                if (published == num_tokens && tx_drained(state, channel, num_tokens))
                    local_store(&queues.tx_finished, 1);
                if (local_load(&queues.tx_finished) && local_load(&queues.rx_finished))
                    queues.tx_action = -1;
                if ((++rounds & 255) == 0 && advanced_failed(state, start)) {
                    advanced_record_error(state, kErrorRingProgressWait);
                    local_store(&queues.abort, 1);
                }
            }
        }
        __syncwarp();
        const int action = queues.tx_action;
        if (action < 0)
            break;
        if (action) {
            auto& stage = queues.tx[queues.tx_stage];
            const int token = state.channel_remote_indices[channel * state.base.layout.num_max_tokens_per_rank + stage.ticket];
            prepare_current_metadata(state, &stage.metadata, token, lane);
            if (!lane) {
                if (prepared > published && local_load(&queues.tx[(prepared - 1) % state.stages].workers_done) < 3)
                    statistics[3]++;
                local_store(&stage.ready, prepared + 1);
            }
            // Metadata writes overlap the payload workers after task release.
            // Delay the vector containing the last live weight, rather than
            // an unused tail field that a correctness check cannot observe.
            const int last_weight_writer_lane =
                (offsetof(TokenMetadata, weights) + (state.base.layout.num_topk - 1) * sizeof(float)) / sizeof(uint4);
            if (lane == last_weight_writer_lane)
                test_delay(state.metadata_delay_ns);
            const auto slot = std::size_t(channel) * state.base.layout.num_payload_slots + stage.payload_slot;
            metadata_copy_warp(reinterpret_cast<TokenMetadata*>(own + state.shared.source_metadata_offset) + slot, &stage.metadata, lane);
            if (!lane)
                reinterpret_cast<float*>(own + state.shared.source_scale_offset)[slot] = state.payload_dtype ? state.fp8_scales[token] : 1.0f;
            __threadfence_system();
            __syncwarp();
            if (!lane) {
                local_store(&stage.metadata_done, 1);
                ++prepared;
            }
        }
        __syncwarp();
    }
}

__device__ void advanced_rx_control(AdvancedDeviceState state, AdvancedLocalQueues& queues, int channel, int lane) {
    int consumed[kNumMaxRanks] = {};
    int issued = 0, completed = 0, next_source = 0, rounds = 0;
    int expected = 0;
    for (int source = 0; source < state.base.layout.num_ranks; ++source)
        if (source != state.base.local_rank)
            expected += state.expected_receive_counts[channel * state.base.layout.num_ranks + source];
    const auto epoch = *state.base.epoch;
    const auto start = global_time_ns();
    auto* statistics = state.channel_statistics + channel * kNumStatisticsFields;
    while (true) {
        if (!lane) {
            queues.rx_action = 0;
            for (int index = 0; index < state.stages; ++index) {
                auto& stage = queues.rx[index];
                if (!local_load(&stage.ready))
                    continue;
                if (!stage.ack_sent && local_load(&stage.host_readers_done) == 3) {
                    store_release_system(receive_ack(state, stage.source_rank, channel, stage.payload_slot), stage.payload_sequence);
                    stage.ack_sent = 1;
                }
                if (stage.ack_sent && local_load(&stage.workers_done) == 3) {
                    local_store(&stage.ready, 0);
                    ++completed;
                    statistics[kNumHostPayloadReadsField]++;
                }
            }
            if (completed == expected) {
                local_store(&queues.rx_finished, 1);
                queues.rx_action = -1;
            } else if (local_load(&queues.abort)) {
                local_store(&queues.rx_finished, 1);
                queues.rx_action = -1;
            } else if (issued < expected && !local_load(&queues.rx[issued % state.stages].ready)) {
                // Bounded one-source probe; TX-control remains independent.
                const int source = next_source;
                next_source = (next_source + 1) % state.base.layout.num_ranks;
                if (source != state.base.local_rank && consumed[source] <
                    state.expected_receive_counts[channel * state.base.layout.num_ranks + source]) {
                    auto* descriptor = receive_descriptor(state, source, channel, consumed[source]);
                    if (load_acquire_system(&descriptor->ready_sequence) == advanced_sequence(epoch, consumed[source])) {
                        auto& stage = queues.rx[issued % state.stages];
                        stage.ticket = issued;
                        stage.source_rank = source;
                        stage.payload_slot = descriptor->payload_slot;
                        stage.payload_sequence = descriptor->payload_sequence;
                        stage.descriptor_ordinal = consumed[source];
                        stage.ack_sent = 0;
                        stage.workers_done = 0;
                        stage.host_readers_done = 0;
                        queues.rx_stage = issued % state.stages;
                        queues.rx_action = 1;
                    } else {
                        statistics[4]++;
                    }
                }
            }
            if ((++rounds & 255) == 0 && advanced_failed(state, start)) {
                advanced_record_error(state, kErrorRingProgressWait);
                local_store(&queues.abort, 1);
            }
        }
        __syncwarp();
        if (queues.rx_action < 0)
            break;
        if (queues.rx_action) {
            auto& stage = queues.rx[queues.rx_stage];
            metadata_copy_warp(&stage.metadata, receive_metadata(state, stage.source_rank, channel, stage.payload_slot), lane);
            __syncwarp();
            if (!lane) {
                stage.output_row = state.base.source_offsets[stage.source_rank] + stage.metadata.rank_ordinals[state.base.local_rank];
                stage.scale = state.payload_dtype ? *receive_scale(state, stage.source_rank, channel, stage.payload_slot) : 1.0f;
                if (stage.payload_sequence != advanced_sequence(epoch, stage.metadata.token_index)) {
                    advanced_record_error(state, kErrorPayloadSequenceMismatch);
                    local_store(&queues.abort, 1);
                }
                // The full descriptor is now captured. Its credit is separate
                // from the host payload ACK and the later local-stage FREE.
                auto* descriptor = receive_descriptor(state, stage.source_rank, channel, stage.descriptor_ordinal);
                store_release_system(&descriptor->consumed_sequence, advanced_sequence(epoch, stage.descriptor_ordinal));
                ++consumed[stage.source_rank];
                local_store(&stage.ready, issued + 1);
                ++issued;
            }
        }
        __syncwarp();
    }
}

__device__ void advanced_tx_worker(AdvancedDeviceState state, AdvancedLocalQueues& queues, int channel, int warp, int lane) {
    int ticket = 0;
    while (true) {
        auto& stage = queues.tx[ticket % state.stages];
        int action = 0;
        if (!lane) {
            if (local_load(&queues.abort))
                action = -1;
            else if (local_load(&stage.ready) == ticket + 1)
                action = 1;
            else if (local_load(&queues.tx_finished))
                action = -1;
        }
        action = __shfl_sync(0xffffffffu, action, 0);
        if (action < 0)
            break;
        if (action) {
            // shfl broadcasts registers only. This memory-order bridge
            // propagates the leader's acquire to every stage-reading lane.
            __syncwarp();
            const int hidden = state.base.layout.num_hidden;
            const int units = state.payload_dtype ? (hidden % 16 ? hidden : hidden / 16) :
                (hidden % 8 ? hidden : hidden / 8);
            if (warp * 32 + lane == min(95, units - 1))
                test_delay(state.tx_delay_ns);
            copy_tx_payload(state, stage, channel, warp * 32 + lane, 96);
            __threadfence_system();
            __syncwarp();
            if (!lane)
                local_arrive(&stage.workers_done);
            ++ticket;
        }
        __syncwarp();
    }
}

__device__ void advanced_rx_worker(
    AdvancedDeviceState state, AdvancedLocalQueues& queues, int channel, int warp, int lane, std::uint16_t* tiles
) {
    int ticket = 0;
    while (true) {
        auto& stage = queues.rx[ticket % state.stages];
        int action = 0;
        if (!lane) {
            if (local_load(&queues.abort))
                action = -1;
            else if (local_load(&stage.ready) == ticket + 1)
                action = 1;
            else if (local_load(&queues.rx_finished))
                action = -1;
        }
        action = __shfl_sync(0xffffffffu, action, 0);
        if (action < 0)
            break;
        if (action) {
            // Join the leader's ready acquire before other lanes read the
            // stage snapshot; shfl itself supplies no memory ordering.
            __syncwarp();
            const int hidden = state.base.layout.num_hidden;
            const int units = state.payload_dtype ? hidden : (hidden % 8 ? hidden : hidden / 8);
            if (warp * 32 + lane == min(95, units - 1))
                test_delay(state.rx_delay_ns);
            auto* tile = tiles + std::size_t(ticket % state.stages) * state.base.layout.num_hidden;
            copy_rx_payload(state, stage, channel, tile, warp * 32 + lane, 96);
            __threadfence_system();
            __syncwarp();
            if (!lane)
                local_arrive(&stage.host_readers_done);
            if (state.fuse_receive_expand) {
                int readers_ready = 0;
                do {
                    if (!lane)
                        readers_ready = local_load(&queues.abort) ? -1 :
                            (local_load(&stage.host_readers_done) == 3 ? 1 : 0);
                    readers_ready = __shfl_sync(0xffffffffu, readers_ready, 0);
                    if (!readers_ready)
                        __nanosleep(32);
                } while (!readers_ready);
                if (readers_ready > 0) {
                    // Propagate the leader's cross-warp tile acquire to all
                    // lanes before scatter reads any shared payload bytes.
                    __syncwarp();
                    if (warp * 32 + lane == min(95, state.base.layout.num_hidden - 1))
                        test_delay(state.scatter_delay_ns);
                    scatter_rx_tile(state, stage, tile, warp * 32 + lane, 96, &queues.abort);
                }
            } else if (!warp && !lane) {
                save_unique_metadata(state.base, stage.metadata, stage.source_rank, stage.output_row);
            }
            __threadfence_system();
            __syncwarp();
            if (!lane)
                local_arrive(&stage.workers_done);
            ++ticket;
        }
        __syncwarp();
    }
}

// Same protocol with a homogeneous CTA, retained as an ablation baseline. All
// participants reach these barriers; this function is never called by a subset
// of role warps. There is intentionally no cross-token local-stage pipeline.
__device__ void advanced_homogeneous(
    AdvancedDeviceState state, AdvancedLocalQueues& queues, int channel, std::uint16_t* tiles
) {
    const int thread = threadIdx.x;
    const int lane = thread % 32;
    const int ranks = state.base.layout.num_ranks;
    const auto epoch = *state.base.epoch;
    const auto start = global_time_ns();
    int consumed[kNumMaxRanks] = {};
    int reserved[kNumMaxEndpoints] = {};
    int produced = 0, rounds = 0;
    auto* own = state.base.mapped_source_buffers[state.base.local_rank];
    auto* statistics = state.channel_statistics + channel * kNumStatisticsFields;
    if (!thread)
        state.channel_timestamps_ns[channel * 2] = start;

    while (true) {
        for (int source = 0; source < ranks; ++source) {
            if (source == state.base.local_rank)
                continue;
            auto& stage = queues.rx[0];
            if (!thread) {
                queues.rx_action = 0;
                if (consumed[source] < state.expected_receive_counts[channel * ranks + source]) {
                    auto* descriptor = receive_descriptor(state, source, channel, consumed[source]);
                    if (load_acquire_system(&descriptor->ready_sequence) == advanced_sequence(epoch, consumed[source])) {
                        stage.source_rank = source;
                        stage.payload_slot = descriptor->payload_slot;
                        stage.payload_sequence = descriptor->payload_sequence;
                        stage.descriptor_ordinal = consumed[source];
                        queues.rx_action = 1;
                    } else {
                        statistics[4]++;
                    }
                }
            }
            __syncthreads();
            if (queues.rx_action && thread < 32) {
                metadata_copy_warp(&stage.metadata, receive_metadata(state, source, channel, stage.payload_slot), lane);
                __syncwarp();
                if (!lane) {
                    stage.output_row = state.base.source_offsets[source] + stage.metadata.rank_ordinals[state.base.local_rank];
                    stage.scale = state.payload_dtype ? *receive_scale(state, source, channel, stage.payload_slot) : 1.0f;
                    auto* descriptor = receive_descriptor(state, source, channel, stage.descriptor_ordinal);
                    store_release_system(&descriptor->consumed_sequence, advanced_sequence(epoch, stage.descriptor_ordinal));
                    if (stage.payload_sequence != advanced_sequence(epoch, stage.metadata.token_index)) {
                        advanced_record_error(state, kErrorPayloadSequenceMismatch);
                        local_store(&queues.abort, 1);
                    }
                }
            }
            __syncthreads();
            if (queues.rx_action && !queues.abort) {
                const int hidden = state.base.layout.num_hidden;
                const int units = state.payload_dtype ? hidden : (hidden % 8 ? hidden : hidden / 8);
                if (thread == min(255, units - 1))
                    test_delay(state.rx_delay_ns);
                copy_rx_payload(state, stage, channel, tiles, thread, 256);
            }
            __threadfence_system();
            __syncthreads();
            if (queues.rx_action && !queues.abort) {
                if (!thread)
                    store_release_system(receive_ack(state, source, channel, stage.payload_slot), stage.payload_sequence);
                if (state.fuse_receive_expand) {
                    if (thread == min(255, state.base.layout.num_hidden - 1))
                        test_delay(state.scatter_delay_ns);
                    scatter_rx_tile(state, stage, tiles, thread, 256, &queues.abort);
                } else if (!thread) {
                    save_unique_metadata(state.base, stage.metadata, source, stage.output_row);
                }
            }
            __threadfence_system();
            __syncthreads();
            if (!thread && queues.rx_action) {
                ++consumed[source];
                statistics[kNumHostPayloadReadsField]++;
            }
            __syncthreads();
        }

        auto& stage = queues.tx[0];
        if (!thread) {
            queues.tx_action = 0;
            if (!queues.abort && produced < state.channel_num_remote_tokens[channel]) {
                if (tx_payload_available(state, channel, produced, reserved)) {
                    const int token = state.channel_remote_indices[channel * state.base.layout.num_max_tokens_per_rank + produced];
                    stage.payload_slot = produced % state.base.layout.num_payload_slots;
                    stage.payload_sequence = advanced_sequence(epoch, token);
                    stage.endpoints = advanced_endpoint_mask(state, state.base.route_plan[token].destination_mask);
                    stage.ticket = token;
                    for (int endpoint = 0; endpoint < state.shared.num_endpoints; ++endpoint)
                        if (stage.endpoints & (1ull << endpoint))
                            stage.endpoint_ordinals[endpoint] = reserved[endpoint]++;
                    queues.tx_action = 1;
                } else {
                    statistics[5]++;
                }
            }
        }
        __syncthreads();
        if (queues.tx_action && thread < 32) {
            prepare_current_metadata(state, &stage.metadata, stage.ticket, lane);
            const int last_weight_writer_lane =
                (offsetof(TokenMetadata, weights) + (state.base.layout.num_topk - 1) * sizeof(float)) / sizeof(uint4);
            if (lane == last_weight_writer_lane)
                test_delay(state.metadata_delay_ns);
            const auto slot = std::size_t(channel) * state.base.layout.num_payload_slots + stage.payload_slot;
            metadata_copy_warp(reinterpret_cast<TokenMetadata*>(own + state.shared.source_metadata_offset) + slot, &stage.metadata, lane);
            if (!lane)
                reinterpret_cast<float*>(own + state.shared.source_scale_offset)[slot] = state.payload_dtype ? state.fp8_scales[stage.ticket] : 1.0f;
        }
        __syncthreads();
        if (queues.tx_action) {
            const int hidden = state.base.layout.num_hidden;
            const int units = state.payload_dtype ? (hidden % 16 ? hidden : hidden / 16) :
                (hidden % 8 ? hidden : hidden / 8);
            if (thread == min(255, units - 1))
                test_delay(state.tx_delay_ns);
            copy_tx_payload(state, stage, channel, thread, 256);
        }
        __threadfence_system();
        __syncthreads();
        if (!thread && queues.tx_action) {
            for (int endpoint = 0; endpoint < state.shared.num_endpoints; ++endpoint) {
                if (stage.endpoints & (1ull << endpoint)) {
                    auto* descriptor = source_descriptor(state, state.base.local_rank, channel, endpoint, stage.endpoint_ordinals[endpoint]);
                    descriptor->payload_sequence = stage.payload_sequence;
                    descriptor->payload_slot = stage.payload_slot;
                    descriptor->token_index = stage.metadata.token_index;
                    descriptor->rank_ordinal = endpoint < ranks ? stage.metadata.rank_ordinals[endpoint] : 0;
                    store_release_system(&descriptor->ready_sequence, advanced_sequence(epoch, stage.endpoint_ordinals[endpoint]));
                    statistics[7]++;
                }
            }
            ++produced;
            statistics[kNumHostPayloadWritesField]++;
            statistics[kNumDescriptorsPublishedField] += __popcll(stage.metadata.destination_mask & ~(1ull << state.base.local_rank));
        }
        if (!thread) {
            int done = produced == state.channel_num_remote_tokens[channel];
            for (int source = 0; source < ranks; ++source)
                if (source != state.base.local_rank)
                    done &= consumed[source] == state.expected_receive_counts[channel * ranks + source];
            if (done)
                done = tx_drained(state, channel, produced);
            if ((++rounds & 255) == 0 && advanced_failed(state, start)) {
                advanced_record_error(state, kErrorRingProgressWait);
                local_store(&queues.abort, 1);
            }
            if (queues.abort) {
                store_release_system(signal_value_ptr(own, state.shared.channel_abort_offset, channel), epoch);
                done = 1;
            }
            queues.tx_action = done ? -1 : 0;
        }
        __syncthreads();
        if (queues.tx_action < 0)
            break;
    }
}

__global__ void advanced_transport(AdvancedDeviceState state) {
    extern __shared__ __align__(16) unsigned char storage[];
    auto& queues = *reinterpret_cast<AdvancedLocalQueues*>(storage);
    auto* tiles = reinterpret_cast<std::uint16_t*>(storage + kNumAdvancedQueueBytes);
    int entry_failed = 0;
    if (!threadIdx.x) {
        entry_failed = cuda::atomic_ref<std::int64_t, cuda::thread_scope_device>(
            state.base.errors[kErrorCodeField]).load(cuda::memory_order_acquire) != 0;
        queues.abort = 0;
        queues.tx_finished = 0;
        queues.rx_finished = 0;
        for (int index = 0; index < state.stages; ++index) {
            queues.tx[index].ready = 0;
            queues.rx[index].ready = 0;
        }
    }
    // Each thread receives the same immutable entry verdict. Branching on
    // mutable queues.abort here would let an early role change the verdict
    // before another warp enters, stranding peers at the final CTA barrier.
    if (__syncthreads_or(entry_failed))
        return;
    const int channel = blockIdx.x;
    const int warp = threadIdx.x / 32;
    const int lane = threadIdx.x % 32;
    if (!state.warp_specialization)
        advanced_homogeneous(state, queues, channel, tiles);
    else if (warp == 0)
        advanced_tx_control(state, queues, channel, lane);
    else if (warp == 1)
        advanced_rx_control(state, queues, channel, lane);
    else if (warp < 5)
        advanced_tx_worker(state, queues, channel, warp - 2, lane);
    else
        advanced_rx_worker(state, queues, channel, warp - 5, lane, tiles);
    // All role loops have an explicit completion/abort exit. No full-CTA
    // barrier occurs inside a role-specific loop.
    __syncthreads();
    if (!threadIdx.x)
        state.channel_timestamps_ns[channel * 2 + 1] = global_time_ns();
}

